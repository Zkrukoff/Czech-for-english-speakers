// Generates src/styles/dark-palette.css: dark mode by mirroring Tailwind's
// colour scales (50 ↔ 950, 100 ↔ 900, …, 500 stays). Components keep their
// light-mode classes; in dark mode "bg-stone-50" becomes a near-black and
// "text-stone-900" a near-white, with the same contrast relationships.
//
// Run after upgrading Tailwind:  node scripts/gen-dark-palette.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const theme = readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const SCALES = ['stone', 'sky', 'emerald', 'amber', 'rose', 'red', 'violet'];
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

const value = (name) => {
  const m = new RegExp(`--color-${name}:\\s*([^;]+);`).exec(theme);
  if (!m) throw new Error(`--color-${name} not found in tailwindcss/theme.css`);
  return m[1].trim();
};

const lines = [];
for (const scale of SCALES) {
  STEPS.forEach((step, i) => {
    const mirror = STEPS[STEPS.length - 1 - i];
    lines.push(`  --color-${scale}-${step}: ${value(`${scale}-${mirror}`)};`);
  });
}
// Cards (bg-white) sit one step above the page background (stone-50 → stone-950).
lines.push(`  --color-white: ${value('stone-900')};`);
lines.push(`  --color-black: ${value('stone-50')};`);
// Case colours: lighter versions that keep their hue and read on dark backgrounds.
lines.push(
  '  --color-case-nom: #a8a29e;',
  '  --color-case-gen: #f59e0b;',
  '  --color-case-dat: #a78bfa;',
  '  --color-case-acc: #fb7185;',
  '  --color-case-voc: #2dd4bf;',
  '  --color-case-loc: #60a5fa;',
  '  --color-case-ins: #4ade80;',
  // Prague palette: dark paper, deep cream panels, light ink, a brighter Vltava for links.
  '  --color-paper: #100e0c;',
  '  --color-cream: #241f18;',
  '  --color-ink: #f5f1ea;',
  '  --color-vltava: #7fb0ff;',
  '  color-scheme: dark;',
);

const block = lines.join('\n');
const css = `/* Generated by scripts/gen-dark-palette.mjs. Do not edit by hand. */

/* Follow the system setting unless the learner chose light in Settings… */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${block.replace(/^/gm, '  ')}
  }
}

/* …or force dark when chosen in Settings. */
:root[data-theme='dark'] {
${block}
}
`;
writeFileSync(new URL('../src/styles/dark-palette.css', import.meta.url), css);
console.log(`wrote ${lines.length} variables`);
