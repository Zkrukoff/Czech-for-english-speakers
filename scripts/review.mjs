// Native review, made routine.
//   npm run review:export [-- --all]   writes review/batch-NN-*.csv (+ notes) for what's still unreviewed
//   npm run review:import -- <file.csv> applies a filled-in sheet: OK marks reviewed, plain fixes apply,
//                                       risky fixes are held in review/fixes-to-apply.md
//   npm run review:status              updates src/generated/review-status.json (the in-app count)
// See docs/REVIEWERS.md.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { BATCHES, CONTENT, ROOT, jsonItems, locate, mdItems } from './lib/review-items.mjs';

const REVIEW = join(ROOT, 'review');
const LOG = join(REVIEW, 'log.json');
const STATUS = join(ROOT, 'src/generated/review-status.json');
const COLUMNS = ['key', 'batch', 'czech', 'english', 'context', 'check', 'verdict', 'corrected_czech', 'comment', 'reviewer'];

// ---------- CSV (RFC 4180; UTF-8 with a BOM so Excel reads the diacritics) ----------
const cell = (v) => {
  const s = String(v ?? '');
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
export const toCsv = (rows) => '﻿' + rows.map((r) => r.map(cell).join(',')).join('\r\n') + '\r\n';
export function parseCsv(text) {
  text = text.replace(/^﻿/, '');
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((x) => x !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) { row.push(field); if (row.some((x) => x !== '')) rows.push(row); }
  return rows;
}

const readLog = () => (existsSync(LOG) ? JSON.parse(readFileSync(LOG, 'utf8')) : { $comment: 'Native review history: what was imported, when, and by whom (initials only).', imports: [], pages: {} });
const today = () => new Date().toISOString().slice(0, 10);

function allItems() {
  const log = readLog();
  const md = mdItems().map((m) => ({ ...m, reviewed: m.flagged ? m.reviewed : !!log.pages[m.file] }));
  return [...jsonItems().map((i) => ({ ...i, reviewed: i.obj.nativeReviewed === true })), ...md];
}

// ---------- status ----------
export function status(items = allItems()) {
  const areas = {};
  for (const i of items) {
    const a = (areas[i.area] ??= { total: 0, reviewed: 0 });
    a.total++; if (i.reviewed) a.reviewed++;
  }
  const s = { $comment: 'Generated by npm run review:status. Do not edit.', total: items.length, reviewed: items.filter((i) => i.reviewed).length, areas: Object.fromEntries(Object.entries(areas).sort()) };
  mkdirSync(join(ROOT, 'src/generated'), { recursive: true });
  writeFileSync(STATUS, JSON.stringify(s, null, 2) + '\n');
  return s;
}

// ---------- export ----------
function relatedNotes(batch) {
  const text = readFileSync(join(CONTENT, 'REVIEW_NEEDED.md'), 'utf8');
  const words = { emergency: /emergency/i, 'line-a-units-1-2': /u0[12]|unit[s]? 1|lesson/i, sounds: /alphabet|pronunciation|sound/i, 'core-words': /vocabulary deck|Step 3/i, 'exam-mock-1': /exam/i, phrases: /phrase deck|Fráze/i, 'line-a-units-3-5': /u0[345]/i, words: /vocabulary|deck/i, exam: /exam/i, guides: /guide/i, holidays: /holiday|name day/i, 'grammar-and-verbs': /grammar|verb|aspect|word order/i, other: /overheard|idiom/i }[batch.slug];
  return text.split(/\n(?=## )/).filter((sec) => sec.startsWith('## ') && words?.test(sec.split('\n')[0])).join('\n\n');
}

function exportBatches(all) {
  const items = allItems().filter((i) => all || !i.reviewed);
  // Keep the history and follow-ups; regenerate the sheets.
  const keep = ['log.json', 'fixes-to-apply.md'].filter((f) => existsSync(join(REVIEW, f))).map((f) => [f, readFileSync(join(REVIEW, f))]);
  const index = [];
  // Sheets of about an hour's work each (by a rough estimate per kind of item).
  const cost = (i) => (i.kind === 'exam' || i.kind === 'page' ? 6 : i.kind === 'exercise' ? 1 : 0.4);
  const split = (rows) => {
    const out = [[]]; let t = 0;
    for (const r of rows) { if (t + cost(r) > 60 && out.at(-1).length) { out.push([]); t = 0; } out.at(-1).push(r); t += cost(r); }
    return out;
  };
  for (const f of existsSync(REVIEW) ? readdirSync(REVIEW) : []) if (/^batch-.*\.(csv|md)$/.test(f)) rmSync(join(REVIEW, f));
  mkdirSync(REVIEW, { recursive: true });
  for (const [f, data] of keep) writeFileSync(join(REVIEW, f), data);
  for (const b of BATCHES) {
    const rows = items.filter((i) => i.batch.n === b.n).sort((x, y) => x.key.localeCompare(y.key));
    if (!rows.length) continue;
    const chunks = split(rows);
    const parts = chunks.length;
    for (let p = 0; p < parts; p++) {
      const chunk = chunks[p];
      const base = `batch-${String(b.n).padStart(2, '0')}-${b.slug}${parts > 1 ? `-part-${p + 1}` : ''}`;
      writeFileSync(join(REVIEW, `${base}.csv`), toCsv([COLUMNS, ...chunk.map((i) => [i.key, b.n, i.cs, i.en, i.context, i.check, '', '', '', ''])]));
      const minutes = Math.round(chunk.reduce((t, i) => t + cost(i), 0));
      const notes = relatedNotes(b);
      writeFileSync(join(REVIEW, `${base}.md`), [
        `# Batch ${b.n}${parts > 1 ? `, part ${p + 1} of ${parts}` : ''}: ${b.title}`, '',
        `${chunk.length} items, roughly ${minutes < 90 ? `${minutes} minutes` : `${Math.round(minutes / 6) / 10} hours`}. Sheet: \`${base}.csv\`. How to fill it in: docs/REVIEWERS.md.`, '',
        'For each row, put **OK**, **Fix** or **Unsure** in `verdict`. For Fix, write the corrected Czech in `corrected_czech` (or explain in `comment`). Put your initials in `reviewer`. Leave rows blank if you skip them.', '',
        notes ? `## Questions we already have about this batch\n\n${notes.replace(/^## /gm, '### ')}` : '',
      ].join('\n'));
      index.push(`| ${b.n}${parts > 1 ? `.${p + 1}` : ''} | ${b.title}${parts > 1 ? ` (part ${p + 1} of ${parts})` : ''} | ${chunk.length} | about ${minutes} min | [${base}.csv](${base}.csv) · [notes](${base}.md) |`);
    }
  }
  writeFileSync(join(REVIEW, 'README.md'), [
    '# Review sheets', '',
    'Generated by `npm run review:export`; only items not yet reviewed are listed. Send a reviewer the sheet and its notes (the .md next to it), then import what comes back with `npm run review:import -- review/<file>.csv`. Guide for reviewers: [docs/REVIEWERS.md](../docs/REVIEWERS.md).', '',
    '| Batch | What | Items | Time | Sheet |', '|---|---|---|---|---|', ...index, '',
  ].join('\n'));
  const s = status();
  console.log(`Exported ${items.length} unreviewed items in ${index.length} sheets to ${REVIEW}/. Reviewed so far: ${s.reviewed} of ${s.total}.`);
}

// ---------- import ----------
/** Runs the content tests; throws if they fail. */
function runContentTests() {
  execFileSync('npx', ['vitest', 'run', 'tests/content.test.ts', 'tests/exam-content.test.ts', 'tests/word-decks.test.ts', 'tests/phrases.test.ts'], { stdio: 'pipe', cwd: ROOT });
}

function importSheet(file, { validate = runContentTests } = {}) {
  const rows = parseCsv(readFileSync(file, 'utf8'));
  const header = rows.shift()?.map((h) => h.trim().toLowerCase());
  const col = (name) => header?.indexOf(name) ?? -1;
  for (const c of ['key', 'czech', 'verdict', 'corrected_czech', 'comment', 'reviewer']) if (col(c) < 0) throw new Error(`${file}: missing column "${c}". Use a sheet made by review:export.`);
  const items = new Map(allItems().map((i) => [i.key, i]));
  const docs = new Map(); // file → parsed JSON or md text
  const load = (f, md) => { if (!docs.has(f)) docs.set(f, md ? readFileSync(join(CONTENT, f), 'utf8') : JSON.parse(readFileSync(join(CONTENT, f), 'utf8'))); return docs.get(f); };
  const report = { ok: 0, fixed: 0, held: [], unsure: [], comments: [], problems: [] };
  const log = readLog();
  const initials = new Set();

  for (const r of rows) {
    const key = r[col('key')]?.trim(), verdict = (r[col('verdict')] ?? '').trim().toLowerCase();
    const corrected = (r[col('corrected_czech')] ?? '').trim(), comment = (r[col('comment')] ?? '').trim(), who = (r[col('reviewer')] ?? '').trim().slice(0, 8);
    if (!key || !verdict) continue;
    if (who) initials.add(who);
    const item = items.get(key);
    if (!item) { report.problems.push(`${key}: no such item (content changed since export?)`); continue; }
    if ((r[col('czech')] ?? '') !== item.cs) { report.problems.push(`${key}: the Czech changed since this sheet was exported; skipped. Export a fresh sheet for it.`); continue; }
    if (comment) report.comments.push({ key, who, comment, verdict });
    if (verdict === 'ok') {
      if (item.md) {
        if (item.flagged) docs.set(item.file, load(item.file, true).replace(/^nativeReviewed:\s*false\s*$/m, 'nativeReviewed: true'));
        else log.pages[item.file] = { reviewed: true, by: who, date: today() };
      } else locate(load(item.file), item.path).nativeReviewed = true;
      report.ok++;
    } else if (verdict === 'fix') {
      if (!item.md && item.autoFix && corrected && !corrected.includes('[[')) {
        const o = locate(load(item.file), item.path);
        report.applied ??= [];
        report.applied.push({ key, from: o.cs, to: corrected, who });
        o.cs = corrected;
        o.nativeReviewed = true;
        report.fixed++;
      } else {
        report.held.push({ key, current: item.cs, corrected, comment, who, why: item.md ? 'a page' : !item.autoFix ? 'answers, lens markup or several fields depend on it' : 'no corrected Czech given' });
      }
    } else if (verdict === 'unsure') report.unsure.push({ key, current: item.cs, comment, who });
    else report.problems.push(`${key}: verdict "${verdict}" isn't OK, Fix or Unsure`);
  }

  // Write, validate, and roll back if anything breaks.
  const backups = [];
  for (const [f, doc] of docs) {
    const p = join(CONTENT, f);
    const before = readFileSync(p, 'utf8');
    const after = typeof doc === 'string' ? doc : JSON.stringify(doc, null, 2) + (before.endsWith('\n') ? '\n' : '');
    if (after === before) continue;
    copyFileSync(p, p + '.bak');
    backups.push(p);
    writeFileSync(p, after);
  }
  if (validate && backups.length) {
    try {
      validate();
    } catch (e) {
      for (const p of backups) { copyFileSync(p + '.bak', p); rmSync(p + '.bak'); }
      throw new Error(`The content no longer validates with these changes, so nothing was changed.\n${String(e.stdout ?? e).slice(-2000)}`);
    }
  }
  for (const p of backups) rmSync(p + '.bak', { force: true });

  log.imports.push({ date: today(), file: file.split('/').pop(), reviewers: [...initials], ok: report.ok, fixed: report.fixed, held: report.held.length, unsure: report.unsure.length });
  mkdirSync(REVIEW, { recursive: true });
  writeFileSync(LOG, JSON.stringify(log, null, 2) + '\n');
  if (report.held.length || report.unsure.length || report.comments.length || report.applied?.length) {
    const lines = [`\n## ${today()} · ${file.split('/').pop()}\n`];
    for (const a of report.applied ?? []) lines.push(`- **Applied** \`${a.key}\`: “${a.from}” → “${a.to}” (${a.who})`);
    for (const h of report.held) lines.push(`- [ ] **To apply by hand** \`${h.key}\` (${h.why}): now “${h.current.replace(/\n/g, ' ⏎ ')}”${h.corrected ? ` → suggested “${h.corrected}”` : ''}${h.comment ? `. Comment: ${h.comment}` : ''} (${h.who})`);
    for (const u of report.unsure) lines.push(`- [ ] **Unsure** \`${u.key}\`: “${u.current.replace(/\n/g, ' ⏎ ')}”${u.comment ? `. ${u.comment}` : ''} (${u.who})`);
    for (const c of report.comments.filter((c) => c.verdict === 'ok')) lines.push(`- Note on \`${c.key}\` (OK): ${c.comment} (${c.who})`);
    const fx = join(REVIEW, 'fixes-to-apply.md');
    writeFileSync(fx, (existsSync(fx) ? readFileSync(fx, 'utf8') : '# Review follow-ups\n\nCorrections and questions from native review that need a person to apply or answer. Tick each one off when done.\n') + lines.join('\n') + '\n');
  }
  const s = status();
  console.log(`Imported ${file}: ${report.ok} OK, ${report.fixed} fixed, ${report.held.length} held for hand-editing, ${report.unsure.length} unsure.`);
  for (const p of report.problems) console.log(`  ! ${p}`);
  console.log(`Reviewed so far: ${s.reviewed} of ${s.total}.`);
  return report;
}

const [cmd, ...args] = process.argv.slice(2);
if (cmd === 'export') exportBatches(args.includes('--all'));
else if (cmd === 'import') {
  if (!args[0]) { console.error('Usage: npm run review:import -- <file.csv>'); process.exit(1); }
  try { importSheet(args[0], args.includes('--no-validate') ? { validate: false } : {}); } catch (e) { console.error(e.message); process.exit(1); }
} else if (cmd === 'status') { const s = status(); console.log(`Reviewed: ${s.reviewed} of ${s.total}.`); }
else if (cmd) { console.error(`Unknown command "${cmd}". Use export, import or status.`); process.exit(1); }
export { importSheet, exportBatches };
